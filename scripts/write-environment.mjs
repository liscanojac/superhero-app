import 'dotenv/config';
import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = resolve(__dirname, '..');
const outFile = resolve(root, 'src/environments/environment.generated.ts');

const apiKey = process.env.SUPERHERO_API_KEY ?? '';

const contents = `/* Generated by scripts/write-environment.mjs — do not edit by hand */
export const environment = {
  production: true,
  apiUrl: 'https://www.superheroapi.com/api.php',
  apiKey: ${JSON.stringify(apiKey)},
};
`;

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, contents, 'utf8');
console.log('Wrote', outFile, apiKey ? '(api key set)' : '(api key empty)');